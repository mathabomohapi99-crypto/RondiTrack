import createClient from 'openapi-fetch';
import type { paths } from './schema'; // generated by npm run api:types, never edited by hand
import { authFetch } from '../auth/session';
import { ApiError } from './apiError';
import { API_BASE_URL } from './config';

// The one client for the whole app; authFetch adds the token and handles refresh
export const api = createClient<paths>({ baseUrl: API_BASE_URL, fetch: authFetch });

// Returns the data or throws an ApiError (status + problem body + Retry-After)
export async function unwrap<T>(result: {
  data?: T;
  error?: unknown;
  response: Response;
}): Promise<T> {
  if (result.response.ok && result.data !== undefined) return result.data;
  const problem =
    result.error && typeof result.error === 'object'
      ? (result.error as Record<string, unknown>)
      : null;
  throw new ApiError(result.response.status, problem, result.response.headers.get('Retry-After'));
}